void main(){
  int a = 12 + 34;
  int b = 23 - 5;
  int c = 23 * 2;
  double d = 34 / 2;
  int e = 44 % 5;
  print(a);
  print(b);
  print(c);
  print(d);
  print(e);

  // a = a + 1;
  print(a++);
  print(a);
  // a = a - 1;
  print(--a);
  print(a);

  a+=12; // a = a + 12;
  a-=23; // a = a - 23;
}